(function () {
  if (window.QB_EXPANDED) {
    for (const k of Object.keys(window.QB_EXPANDED)) {
      if (window.QB[k]) {
        window.QB[k] = window.QB[k].concat(window.QB_EXPANDED[k] || []);
      }
    }
  }
  // 加载用户通过 import.html 导入的自定义题目
  loadCustomQuestions();
})();

function loadCustomQuestions() {
  try {
    const customKey = 'shangAnTong_custom_questions';
    const customIds = JSON.parse(localStorage.getItem(customKey) || '{}');
    const storedKey = 'shangAnTong_custom_data';
    const storedData = JSON.parse(localStorage.getItem(storedKey) || '{}');
    let hasCustom = false;
    Object.keys(customIds).forEach(mod => {
      if (!window.QB[mod]) window.QB[mod] = [];
      customIds[mod].forEach(id => {
        if (!window.QB[mod].some(q => q.id === id) && storedData[id]) {
          window.QB[mod].push(storedData[id]);
          hasCustom = true;
        }
      });
    });
    if (hasCustom) {
      window.QB_STATS.total = Object.keys(window.QB).reduce((s, k) => s + window.QB[k].length, 0);
    }
  } catch (e) {}
}

// 题库统计
window.QB_STATS = (function () {
  let total = 0;
  Object.keys(window.QB).forEach(k => total += window.QB[k].length);
  return { total };
})();
